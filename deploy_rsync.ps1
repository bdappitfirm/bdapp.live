# ====================================================================
# deploy_rsync.ps1  -  LOCAL -> LIVE  (CODE ONLY, never reverse)
# ====================================================================
#
# PURPOSE:
#   Packages LOCAL source code + React build and deploys it to the
#   LIVE VPS server.  Runs ONLY on the developer's Windows machine.
#
# CRITICAL WORKFLOW SEPARATION (MUST NEVER BE MIXED):
#   ------------------------------------------------------------------
#   deploy_rsync.ps1      = CODE DEPLOY    : LOCAL  -> LIVE
#   sync_live_to_local.ps1= DATA SYNC (DB) : LIVE   -> LOCAL
#   ------------------------------------------------------------------
#
# FORBIDDEN HERE (by design):
#   - NO LIVE -> LOCAL code/file pull of any kind
#   - NO LIVE database DUMP / pg_dump here (lives in sync script)
#   - NO LIVE database overwrite / TRUNCATE on deploy
#   - NO migration restore, schema restore, or django_migrations copy
#   - NO upload of the developer's local DB/media to LIVE
# ====================================================================

$VPS_IP     = "103.112.62.72"
$USER       = "root"
$REMOTE_DIR = "/var/www/bdapp"

Write-Host "========================================" -ForegroundColor Cyan
Write-Host "  LOCAL -> LIVE : CODE DEPLOY ONLY     " -ForegroundColor Cyan
Write-Host "  (LIVE data stays on LIVE server)     " -ForegroundColor Cyan
Write-Host "========================================" -ForegroundColor Cyan

# 1) Build the React frontend
Write-Host "[1/4] Building React frontend..." -ForegroundColor Yellow
Push-Location "frontend"
try {
    & npm.cmd run build
    if ($LASTEXITCODE -ne 0) { throw "Frontend build failed." }
} finally {
    Pop-Location
}

# 2) Bundle ONLY source-code artifacts, NEVER local data/local DB/media
$timestamp = Get-Date -Format "yyyyMMddHHmmss"
$zipName   = "deploy_$timestamp.tar.gz"

Write-Host "[2/4] Packing CODE ONLY into $zipName ..." -ForegroundColor Yellow
# NOTE: Explicitly exclude ALL developer-local state (media, DB dumps, venv,
#       node_modules, staticfiles generated by collectstatic, pyc, archives).
$tarArgs = @(
    "-czf", $zipName,
    "--exclude=media",
    "--exclude=media_local",
    "--exclude=staticfiles",
    "--exclude=.venv",
    "--exclude=venv",
    "--exclude=node_modules",
    "--exclude=frontend/node_modules",
    "--exclude=__pycache__",
    "--exclude=*.pyc",
    "--exclude=*.tar",
    "--exclude=*.tar.gz",
    "--exclude=*.zip",
    "--exclude=db_*.json",
    "--exclude=*.sql",
    "--exclude=*.dump",
    "backend", "users", "schools", "academics", "attendance", "fees", "results",
    "manage.py", "requirements.txt", "scripts",
    "fix_all.sh", "fix_database_marks.py", "auto_translate.py",
    "fix_db_schema.py", "cleanup_orphaned_students.py", "school_19_students.json",
    "frontend/build"
)
& tar @tarArgs
if ($LASTEXITCODE -ne 0) { throw "tar pack failed." }

# 3) Upload bundle to LIVE /tmp (not into application tree yet)
Write-Host "[3/4] Uploading bundle to LIVE /tmp ..." -ForegroundColor Yellow
& ".\pscp.exe" -v $zipName "${USER}@${VPS_IP}:/tmp/deploy_latest.tar.gz"
if ($LASTEXITCODE -ne 0) {
    Write-Error "Upload to LIVE failed (pscp exit $LASTEXITCODE)."
    if (Test-Path $zipName) { Remove-Item $zipName -Force }
    exit 1
}

# 4) On LIVE: extract + run fix_all.sh (migrations + collectstatic + restart)
Write-Host "[4/4] Applying CODE on LIVE server (migrations + restart)..." -ForegroundColor Cyan
$remoteDeployCmd = @"
set -e
# Safety: never touch DB dumps / media / migrations-table rows via untar
rm -rf $REMOTE_DIR/frontend/build
tar -xzf /tmp/deploy_latest.tar.gz -C $REMOTE_DIR/
chmod +x $REMOTE_DIR/fix_all.sh
rm -f /tmp/deploy_latest.tar.gz
$REMOTE_DIR/fix_all.sh
"@
& ssh "${USER}@${VPS_IP}" $remoteDeployCmd
if ($LASTEXITCODE -ne 0) { Write-Error "LIVE-side extraction/fix_all.sh exited $LASTEXITCODE." }

# Local cleanup
if (Test-Path $zipName)      { Remove-Item $zipName -Force }
if (Test-Path "deploy.tar.gz") { Remove-Item "deploy.tar.gz" -Force -ErrorAction SilentlyContinue }

Write-Host "========================================" -ForegroundColor Green
Write-Host "  `u{2705} CODE DEPLOY (LOCAL -> LIVE) COMPLETE" -ForegroundColor Green
Write-Host "  Browser hard-refresh: Ctrl+F5"      -ForegroundColor White
Write-Host "  (To pull LIVE DATA: .\sync_live_to_local.ps1)" -ForegroundColor DarkGray
Write-Host "========================================" -ForegroundColor Green
